const maps = [propMap, optionMap, elementMap, categoryMap, groupMap];

/**
 * 翻译元数据标签
 * @param label 中文标签
 * @param language 目标语言
 * @returns 翻译后的标签
 */
export function translateLabel(label: string, language: Language): string {
  if (language === 'zh') return label;

  // 按优先级查找：属性 > 选项 > 元素 > 分类 > 分组
  for (const map of maps) {
    const key = map[label];
    if (key && translations[language][key]) {
      return translations[language][key];
    }
  }

  return label;
}